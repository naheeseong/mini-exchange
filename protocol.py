"""
protocol.py — 거래소 서버와 트레이더 클라이언트가 함께 쓰는 공통 설정과 메시지 형식

서버와 클라이언트가 "같은 언어"로 말해야 통신이 되므로,
주소/포트, 종목 목록, 메시지를 바이트로 바꾸는 방법을 한 곳에 모아 둔다.
"""

import json
import time

# ---------------------------------------------------------------------------
# 1) UDP 멀티캐스트 설정 (시세 방송용)
# ---------------------------------------------------------------------------
# 224.0.0.0 ~ 239.255.255.255 는 "멀티캐스트 전용" IP 대역이다.
# 이 주소는 특정 컴퓨터 하나가 아니라 "그룹"을 가리킨다.
# 서버는 그룹 주소로 한 번만 보내고, 그룹에 가입(IGMP Join)한 수신자는 모두 같은 패킷을 받는다.
# → 트레이더가 100명이어도 서버는 100번이 아니라 1번만 보내면 된다 (1:N 전송).
MCAST_GROUP = "224.1.1.1"
MCAST_PORT = 5007

# TTL(Time To Live): 패킷이 라우터를 몇 번 넘어갈 수 있는지.
# 1 이면 같은 네트워크(LAN) 밖으로 나가지 않는다 → 과제용 시세가 인터넷으로 새지 않게 막는다.
MCAST_TTL = 1

# 멀티캐스트 패킷을 내보내고 받을 네트워크 인터페이스(내 컴퓨터의 IP).
# "0.0.0.0" 이면 운영체제가 기본 인터페이스를 골라준다.
# 와이파이가 꺼져 있어서 멀티캐스트가 안 될 때는 실행 옵션 --iface 127.0.0.1 로 바꿀 수 있다.
MCAST_IFACE = "0.0.0.0"

# UDP 데이터그램 한 개의 최대 수신 크기. 시세 메시지는 200바이트 정도라 넉넉하다.
UDP_BUFFER_SIZE = 4096

# ---------------------------------------------------------------------------
# 2) TCP 설정 (주문/체결용) — 2단계에서 사용
# ---------------------------------------------------------------------------
TCP_HOST = "127.0.0.1"
TCP_PORT = 6000

# ---------------------------------------------------------------------------
# 3) 거래소 설정
# ---------------------------------------------------------------------------
# 가상 종목과 시작 가격(원)
INITIAL_PRICES = {
    "SJU": 50000,
    "KBK": 72000,
    "NET": 13500,
}

# 시세를 몇 초마다 바꾸고 방송할지 (0.1초 = 초당 10번)
TICK_INTERVAL = 0.1


# ---------------------------------------------------------------------------
# 4) 메시지 인코딩/디코딩
# ---------------------------------------------------------------------------
# 소켓은 "바이트"만 주고받을 수 있다. 파이썬 dict 를 그대로 보낼 수 없으므로
#   dict → JSON 문자열 → UTF-8 바이트   (보낼 때, encode)
#   바이트 → JSON 문자열 → dict         (받을 때, decode)
# 로 바꾼다. JSON 은 사람이 읽을 수 있어서 Wireshark 로 패킷을 봐도 내용이 보인다.

def encode(message: dict) -> bytes:
    """dict 메시지를 네트워크로 보낼 바이트로 변환한다."""
    return json.dumps(message, ensure_ascii=False).encode("utf-8")


def decode(data: bytes) -> dict:
    """네트워크에서 받은 바이트를 dict 메시지로 되돌린다."""
    return json.loads(data.decode("utf-8"))


def now_ms() -> float:
    """현재 시각을 밀리초(ms) 단위로 돌려준다. 지연(latency) 계산에 쓴다.

    주의: 서버와 클라이언트가 '같은 컴퓨터'일 때만 시계가 같아서 지연이 정확하다.
    서로 다른 컴퓨터라면 두 시계의 차이(clock skew)만큼 오차가 생긴다.
    """
    return time.time() * 1000


